CONTEXTO_ADJETIVO_CALMA = re.compile(
    r"\b(?:está|esta|estava|estão|estao|estavam|fica|ficou|ficavam|"
    r"permanece|permaneceu|permanecia|parece|pareceu|continuava|"
    r"continua|continuou|sentia-se|sentiu-se)"
    r"(?:\s+(?:muito|bem|mais|menos|bastante|tão))?\s+$",
    re.IGNORECASE,
)


def _pode_substituir(texto, trecho):
    palavra = trecho.group().lower()
    if palavra != "calma":
        return True
    # "calma" funciona como substantivo em "mantenha a calma" e como
    # adjetivo em "a menina estava calma". Só alteramos o segundo uso.
    return bool(CONTEXTO_ADJETIVO_CALMA.search(texto[:trecho.start()]))


def trocar_palavras(texto, limite=2, semente=42):
    texto = unicodedata.normalize("NFC", texto)
    rng = random.Random(semente)
    candidatos = [m for m in PADRAO_PALAVRA.finditer(texto)
                  if m.group().lower() in SINONIMOS
                  and SINONIMOS[m.group().lower()]
                  and _pode_substituir(texto, m)]
    quantidade = min(max(0, int(limite)), len(candidatos))
    escolhidos = sorted(rng.sample(candidatos, quantidade), key=lambda m: m.start())
    partes, alteracoes, cursor = [], [], 0
    for trecho in escolhidos:
        original = trecho.group()
        nova = rng.choice(SINONIMOS[original.lower()])
        if original.isupper():
            nova = nova.upper()
        elif original.istitle():
            nova = nova.capitalize()
        partes.extend([texto[cursor:trecho.start()], nova])
        alteracoes.append({"original": original, "nova": nova, "inicio": trecho.start()})
        cursor = trecho.end()
    partes.append(texto[cursor:])
    return "".join(partes), alteracoes
